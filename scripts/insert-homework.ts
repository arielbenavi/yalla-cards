  if (existing && existing.length > 0) {
    console.log(`ℹ️  מוחק ${existing.length} שיעורי בית קיימים ומכניס מחדש...`);
    await sb.from("homework").delete().not("id", "is", null);
  }

  const { data, error } = await sb.from("homework").insert(homeworks).select("id, title");
