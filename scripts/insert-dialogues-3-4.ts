async function main() {
  for (const entry of [MEETING_3, MEETING_4]) {
    const { error } = await supabase
      .from("paradigms")
      .upsert(entry, { onConflict: "meeting,slug" });

    if (error) {
      console.error(`Meeting ${entry.meeting} error:`, error.message);
      return;
    }
    console.log(`✓ Meeting ${entry.meeting} translation_sentences inserted (${(entry.data as any).sentences.length} sentences)`);
  }
}

main();
